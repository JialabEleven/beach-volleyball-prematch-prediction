def read_csv_fallback(path):
    try:
        return pd.read_csv(path, encoding="utf-8", low_memory=False)
    except UnicodeDecodeError:
        return pd.read_csv(path, encoding="latin-1", low_memory=False)


def load_data(path):
    df = read_csv_fallback(path)

    if "date" not in df.columns:
        raise ValueError("Input file must contain a 'date' column.")
    if "y" not in df.columns:
        raise ValueError("Input file must contain target column 'y'.")

    df["date"] = pd.to_datetime(df["date"], errors="coerce")
    if df["date"].isna().any():
        raise ValueError(
            f"Invalid/missing dates: {int(df['date'].isna().sum())}"
        )

    df["y"] = pd.to_numeric(df["y"], errors="raise").astype(int)

    sort_cols = ["date"]
    if "match_num" in df.columns:
        sort_cols.append("match_num")

    return df.sort_values(
        sort_cols,
        kind="mergesort"
    ).reset_index(drop=True)


def split_by_time(df, train_end="2017-12-31", valid_end="2019-12-31"):
    train_end = pd.Timestamp(train_end)
    valid_end = pd.Timestamp(valid_end)

    train = df[df["date"] <= train_end].copy().reset_index(drop=True)
    valid = df[
        (df["date"] > train_end) &
        (df["date"] <= valid_end)
    ].copy().reset_index(drop=True)
    test = df[df["date"] > valid_end].copy().reset_index(drop=True)

    return train, valid, test


def make_xy(df):
    missing = [c for c in FEATURE_COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(
            "Missing required baseline feature columns:\n" +
            "\n".join(missing)
        )

    X = df[FEATURE_COLUMNS].copy()
    y = df["y"].astype(int).to_numpy()
    return X, y


def get_num_cat_cols(X):
    num_cols = [c for c in X.columns if is_numeric_dtype(X[c])]
    cat_cols = [c for c in X.columns if c not in num_cols]
    return num_cols, cat_cols


def make_preprocessor(X_train):
    num_cols, cat_cols = get_num_cat_cols(X_train)

    numeric_transformer = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
    ])

    categorical_transformer = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("onehot", OneHotEncoder(handle_unknown="ignore")),
    ])

    return ColumnTransformer([
        ("num", numeric_transformer, num_cols),
        ("cat", categorical_transformer, cat_cols),
    ])


def prepare_catboost_inputs(X_train, X_valid, X_test):
    num_cols, cat_cols = get_num_cat_cols(X_train)

    Xtr = X_train.copy()
    Xva = X_valid.copy()
    Xte = X_test.copy()

    medians = Xtr[num_cols].median(numeric_only=True)

    Xtr[num_cols] = Xtr[num_cols].fillna(medians)
    Xva[num_cols] = Xva[num_cols].fillna(medians)
    Xte[num_cols] = Xte[num_cols].fillna(medians)

    for c in cat_cols:
        mode_series = Xtr[c].mode(dropna=True)
        fill_value = mode_series.iloc[0] if len(mode_series) else "missing"

        Xtr[c] = Xtr[c].fillna(fill_value).astype(str)
        Xva[c] = Xva[c].fillna(fill_value).astype(str)
        Xte[c] = Xte[c].fillna(fill_value).astype(str)

    cat_indices = [Xtr.columns.get_loc(c) for c in cat_cols]

    return Xtr, Xva, Xte, cat_indices


