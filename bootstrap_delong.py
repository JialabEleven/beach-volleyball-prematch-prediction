def load_identity_predictions(path):
    if path is None or not os.path.exists(path):
        print(
            "\nWARNING: Priority-3 identity prediction file not found. "
            "Baseline-vs-identity DeLong test will be skipped."
        )
        return None

    df = pd.read_csv(path)

    required = [
        "y",
        "baseline_has_time_probability_mean_10seeds",
        "identity_has_time_probability_mean_10seeds",
    ]

    missing = [c for c in required if c not in df.columns]

    if missing:
        raise ValueError(
            "Identity prediction file is missing columns:\n" +
            "\n".join(missing)
        )

    return df


