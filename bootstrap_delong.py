def stratified_bootstrap_auc(
    y,
    score_dict,
    n_boot=5000,
    seed=20260903
):
    """
    Paired stratified nonparametric bootstrap.

    The SAME resampled observation indices are used for all models within
    each replicate, preserving the paired nature of model comparisons.
    """
    y = np.asarray(y, dtype=int)

    pos_idx = np.flatnonzero(y == 1)
    neg_idx = np.flatnonzero(y == 0)

    if len(pos_idx) == 0 or len(neg_idx) == 0:
        raise ValueError("Both outcome classes are required for AUC.")

    rng = np.random.default_rng(seed)

    bootstrap_values = {
        name: np.empty(n_boot, dtype=float)
        for name in score_dict
    }

    for b in range(n_boot):
        boot_pos = rng.choice(
            pos_idx,
            size=len(pos_idx),
            replace=True
        )
        boot_neg = rng.choice(
            neg_idx,
            size=len(neg_idx),
            replace=True
        )

        idx = np.concatenate([boot_pos, boot_neg])

        # Shuffle is not required for AUC, but avoids any accidental
        # dependence on class-block ordering in downstream extensions.
        rng.shuffle(idx)

        yb = y[idx]

        for name, score in score_dict.items():
            bootstrap_values[name][b] = roc_auc_score(
                yb,
                np.asarray(score)[idx]
            )

        if (b + 1) % 500 == 0:
            print(f"Bootstrap: {b + 1}/{n_boot}")

    rows = []

    for name, values in bootstrap_values.items():
        point_auc = roc_auc_score(y, score_dict[name])

        lo, hi = np.percentile(
            values,
            [2.5, 97.5]
        )

        rows.append({
            "model": name,
            "auc_point_estimate": float(point_auc),
            "bootstrap_auc_mean": float(np.mean(values)),
            "bootstrap_auc_sd": float(np.std(values, ddof=1)),
            "ci95_lower": float(lo),
            "ci95_upper": float(hi),
            "n_bootstrap": int(n_boot),
        })

    return pd.DataFrame(rows), bootstrap_values


# =====================================================================
# DELONG TEST
# Implementation based on the standard fast DeLong covariance algorithm.
# =====================================================================

def compute_midrank(x):
    """
    Midranks with ties. Returned ranks are 1-based as required by
    the DeLong derivation.
    """
    x = np.asarray(x)
    order = np.argsort(x)
    sorted_x = x[order]

    n = len(x)
    ranks_sorted = np.zeros(n, dtype=float)

    i = 0
    while i < n:
        j = i
        while j < n and sorted_x[j] == sorted_x[i]:
            j += 1

        ranks_sorted[i:j] = 0.5 * (i + j - 1) + 1.0
        i = j

    ranks = np.empty(n, dtype=float)
    ranks[order] = ranks_sorted

    return ranks


def fast_delong(predictions_sorted_transposed, label_1_count):
    """
    Fast DeLong covariance calculation.

    predictions_sorted_transposed:
        shape = (n_classifiers, n_examples)
        examples ordered with positives first, negatives second.
    """
    m = int(label_1_count)
    n = predictions_sorted_transposed.shape[1] - m
    k = predictions_sorted_transposed.shape[0]

    if m <= 0 or n <= 0:
        raise ValueError("DeLong requires both positive and negative examples.")

    positive_examples = predictions_sorted_transposed[:, :m]
    negative_examples = predictions_sorted_transposed[:, m:]

    tx = np.empty((k, m), dtype=float)
    ty = np.empty((k, n), dtype=float)
    tz = np.empty((k, m + n), dtype=float)

    for r in range(k):
        tx[r, :] = compute_midrank(positive_examples[r, :])
        ty[r, :] = compute_midrank(negative_examples[r, :])
        tz[r, :] = compute_midrank(predictions_sorted_transposed[r, :])

    aucs = tz[:, :m].sum(axis=1) / (m * n) - (m + 1.0) / (2.0 * n)

    v01 = (tz[:, :m] - tx) / n
    v10 = 1.0 - (tz[:, m:] - ty) / m

    sx = np.cov(v01)
    sy = np.cov(v10)

    # np.cov returns scalar for k=1; this function is used with k>=2.
    delong_cov = sx / m + sy / n

    return aucs, delong_cov


def delong_test(y_true, score_a, score_b):
    """
    Paired two-sided DeLong test for two correlated ROC AUCs.
    """
    y_true = np.asarray(y_true, dtype=int)
    score_a = np.asarray(score_a, dtype=float)
    score_b = np.asarray(score_b, dtype=float)

    if not (
        len(y_true) == len(score_a) == len(score_b)
    ):
        raise ValueError("y and model scores must have identical lengths.")

    order = np.argsort(-y_true)  # positives first
    y_sorted = y_true[order]

    m = int(np.sum(y_sorted == 1))

    predictions = np.vstack([
        score_a[order],
        score_b[order]
    ])

    aucs, cov = fast_delong(
        predictions,
        m
    )

    diff = float(aucs[0] - aucs[1])

    variance = float(
        cov[0, 0] +
        cov[1, 1] -
        2.0 * cov[0, 1]
    )

    # Numerical safeguard.
    variance = max(variance, 0.0)

    if variance == 0:
        if abs(diff) < 1e-15:
            z = 0.0
            p = 1.0
        else:
            z = math.copysign(float("inf"), diff)
            p = 0.0
    else:
        se = math.sqrt(variance)
        z = diff / se

        # Two-sided standard-normal p-value:
        # 2 * (1 - Phi(|z|)) = erfc(|z| / sqrt(2))
        p = math.erfc(
            abs(z) / math.sqrt(2.0)
        )

    return {
        "auc_model_1": float(aucs[0]),
        "auc_model_2": float(aucs[1]),
        "delta_auc_model1_minus_model2": diff,
        "delong_variance_delta": variance,
        "z": float(z),
        "p_raw": float(p),
    }


def holm_adjust(p_values):
    """
    Holm step-down family-wise error correction.
    """
    p_values = np.asarray(p_values, dtype=float)

    m = len(p_values)
    order = np.argsort(p_values)
    sorted_p = p_values[order]

    adjusted_sorted = np.empty(m, dtype=float)

    running_max = 0.0

    for rank, p in enumerate(sorted_p):
        multiplier = m - rank
        candidate = min(1.0, multiplier * p)
        running_max = max(running_max, candidate)
        adjusted_sorted[rank] = running_max

    adjusted = np.empty(m, dtype=float)
    adjusted[order] = adjusted_sorted

    return adjusted


def pairwise_delong(y, score_dict):
    rows = []

    model_names = list(score_dict.keys())

    for model_a, model_b in itertools.combinations(model_names, 2):
        result = delong_test(
            y,
            score_dict[model_a],
            score_dict[model_b]
        )

        rows.append({
            "model_1": model_a,
            "model_2": model_b,
            **result,
        })

    df = pd.DataFrame(rows)

    df["p_holm"] = holm_adjust(
        df["p_raw"].to_numpy()
    )

    df["significant_raw_0.05"] = (
        df["p_raw"] < 0.05
    )

    df["significant_holm_0.05"] = (
        df["p_holm"] < 0.05
    )

    return df


