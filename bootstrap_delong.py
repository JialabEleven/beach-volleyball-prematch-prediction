def create_sklearn_models(X_train, seed):
    return {
        "Logistic Regression": Pipeline([
            ("preprocessor", make_preprocessor(X_train)),
            ("model", LogisticRegression(
                max_iter=1200,
                random_state=seed
            )),
        ]),

        "Random Forest": Pipeline([
            ("preprocessor", make_preprocessor(X_train)),
            ("model", RandomForestClassifier(
                n_estimators=500,
                max_depth=None,
                min_samples_leaf=2,
                random_state=seed,
                n_jobs=-1,
            )),
        ]),

        "XGBoost": Pipeline([
            ("preprocessor", make_preprocessor(X_train)),
            ("model", XGBClassifier(
                n_estimators=800,
                max_depth=4,
                learning_rate=0.03,
                subsample=0.85,
                colsample_bytree=0.85,
                min_child_weight=3,
                reg_alpha=0.0,
                reg_lambda=2.0,
                eval_metric="logloss",
                random_state=seed,
                n_jobs=-1,
            )),
        ]),
    }


def run_baseline_models(train, valid, test, seeds):
    X_train, y_train = make_xy(train)
    X_valid, y_valid = make_xy(valid)
    X_test, y_test = make_xy(test)

    # CatBoost preprocessing is independent of seed.
    Xtr_cb, Xva_cb, Xte_cb, cat_idx = prepare_catboost_inputs(
        X_train, X_valid, X_test
    )

    rows = []
    test_prob_store = {
        "Logistic Regression": [],
        "Random Forest": [],
        "XGBoost": [],
        "CatBoost": [],
    }

    for seed in seeds:
        print(f"\n===== Baseline seed {seed} =====")

        sklearn_models = create_sklearn_models(X_train, seed)

        for model_name, model in sklearn_models.items():
            model.fit(X_train, y_train)

            valid_prob = model.predict_proba(X_valid)[:, 1]
            test_prob = model.predict_proba(X_test)[:, 1]

            valid_metrics = metric_dict(y_valid, valid_prob)
            test_metrics = metric_dict(y_test, test_prob)

            rows.append({
                "seed": seed,
                "model": model_name,
                **{f"valid_{k}": v for k, v in valid_metrics.items()},
                **{f"test_{k}": v for k, v in test_metrics.items()},
            })

            test_prob_store[model_name].append(test_prob)

            print(
                f"{model_name:20s} "
                f"TEST AUC={test_metrics['auc']:.6f}, "
                f"ACC={test_metrics['accuracy']:.6f}, "
                f"F1={test_metrics['f1']:.6f}, "
                f"LogLoss={test_metrics['logloss']:.6f}"
            )

        cat = CatBoostClassifier(
            iterations=900,
            depth=6,
            learning_rate=0.03,
            loss_function="Logloss",
            eval_metric="AUC",
            random_seed=seed,
            l2_leaf_reg=5,
            subsample=0.85,
            allow_writing_files=False,
            verbose=False,
        )

        cat.fit(
            Xtr_cb,
            y_train,
            cat_features=cat_idx,
            eval_set=(Xva_cb, y_valid),
            use_best_model=True,
            verbose=False,
        )

        valid_prob = cat.predict_proba(Xva_cb)[:, 1]
        test_prob = cat.predict_proba(Xte_cb)[:, 1]

        valid_metrics = metric_dict(y_valid, valid_prob)
        test_metrics = metric_dict(y_test, test_prob)

        rows.append({
            "seed": seed,
            "model": "CatBoost",
            **{f"valid_{k}": v for k, v in valid_metrics.items()},
            **{f"test_{k}": v for k, v in test_metrics.items()},
        })

        test_prob_store["CatBoost"].append(test_prob)

        print(
            f"{'CatBoost':20s} "
            f"TEST AUC={test_metrics['auc']:.6f}, "
            f"ACC={test_metrics['accuracy']:.6f}, "
            f"F1={test_metrics['f1']:.6f}, "
            f"LogLoss={test_metrics['logloss']:.6f}"
        )

    runs_df = pd.DataFrame(rows)

    summary_rows = []
    for model_name, g in runs_df.groupby("model", sort=False):
        row = {"model": model_name, "n_runs": len(g)}

        for split in ["valid", "test"]:
            for metric in ["auc", "accuracy", "f1", "logloss"]:
                c = f"{split}_{metric}"
                row[f"{c}_mean"] = float(g[c].mean())
                row[f"{c}_sd"] = float(g[c].std(ddof=1))

        summary_rows.append(row)

    summary_df = pd.DataFrame(summary_rows)

    mean_probs = {
        model: np.mean(np.vstack(probs), axis=0)
        for model, probs in test_prob_store.items()
    }

    return (
        runs_df,
        summary_df,
        y_test,
        test_prob_store,
        mean_probs
    )


